assert.equal(decode([1,11,124,1]).data.doorOpen,true);
assert.equal(decode([1,255,156,2]).data.temperature,-1);
assert.equal(decode([1,255,156,2]).data.waterDetected,true);
for(const [bytes,port] of [[[1,2],2],[[2,11,124,0],2],[[1,11,124,4],2],[[1,11,124,0],3],[[1,256,0,0],2],[[1,127,255,0],2]])assert.ok(decode(bytes,port).errors);
