for(const node of flow) for(const output of node.wires??[]) for(const destination of output) assert.ok(ids.has(destination));
assert.equal(flow.find(n=>n.type==='mqtt in').topic,'lab/esp32-01/telemetry');
const store=new Map(),warnings=[];
const context=vm.createContext({flow:{get:key=>store.get(key),set:(key,value)=>store.set(key,value)},node:{warn:text=>warnings.push(text)}});
const run=(id,msg)=>{
 context.msg=msg;
 return vm.runInContext('(function(msg){'+flow.find(n=>n.id===id).func+'})(msg)',context);
};
const sample={deviceId:'esp32-01',temperature:29.4,unit:'C',simulated:true};
assert.equal(run('iot-validate',{payload:sample}).payload.temperature,29.4);
assert.match(run('iot-render',{}).payload,/DATA BARU/);
